"""Provision a pilot invoice database: `plain` (app must isolate) or `protected` (RLS).

Standalone: copied into pilot verifier images and the full_tool self-check, so it
imports only psycopg. Creates one restricted login role and one fresh UTF-8
database owned by the administrative connection.

- `plain`: no row-level security. The runtime role may read, insert and update
  every row; only application code can keep tenants apart.
- `protected`: forced row-level security keyed on transaction-local
  `app.tenant_id`, one `tenant_isolation` policy for all commands, and insert or
  update rights only on the content columns. `tenant_id` defaults from context.
"""

import psycopg
from psycopg import sql
from psycopg.conninfo import conninfo_to_dict, make_conninfo

FIXTURES = ("plain", "protected")
TENANTS = {"fixture-alice": "org-a", "fixture-bob": "org-b", "fixture-unassigned": None}
# The graded public data, identical to protocol v3's rows.
GRADING = {
    "tenants": TENANTS,
    "invoices": [
        (1, "org-a", "A consulting", 1200),
        (2, "org-a", "A support", 3400),
        (3, "org-b", "B consulting", 5600),
        (4, "org-b", "B support", 7800),
    ],
}
# The full_tool self-check data: same public identities, disjoint rows.
DEVELOPMENT = {
    "tenants": TENANTS,
    "invoices": [
        (101, "org-a", "A design review", 2500),
        (102, "org-a", "A audit", 4100),
        (103, "org-b", "B design review", 6300),
        (104, "org-b", "B audit", 8900),
    ],
}
_CONTEXT = "nullif(current_setting('app.tenant_id', true), '')"


def provision(admin_dsn, database, role, password, *, fixture, dataset=GRADING):
    """Create the role and database for one fixture; return the setup DSN."""
    if fixture not in FIXTURES:
        raise ValueError(f"fixture must be one of {FIXTURES}")
    with psycopg.connect(admin_dsn, autocommit=True, connect_timeout=5) as admin:
        admin.execute(
            sql.SQL(
                "CREATE ROLE {} LOGIN PASSWORD {} NOSUPERUSER NOBYPASSRLS "
                "NOCREATEDB NOCREATEROLE NOREPLICATION"
            ).format(sql.Identifier(role), sql.Literal(password))
        )
        # Pinned encoding and collation keep exported values identical everywhere.
        admin.execute(
            sql.SQL(
                "CREATE DATABASE {} TEMPLATE template0 ENCODING 'UTF8' LC_COLLATE 'C' LC_CTYPE 'C'"
            ).format(sql.Identifier(database))
        )
    settings = conninfo_to_dict(admin_dsn)
    settings["dbname"] = database
    setup_dsn = make_conninfo(**settings)
    runtime = sql.Identifier(role)
    with psycopg.connect(setup_dsn, autocommit=True, connect_timeout=5) as setup:
        setup.execute(
            sql.SQL("REVOKE ALL ON DATABASE {} FROM PUBLIC").format(sql.Identifier(database))
        )
        setup.execute(
            sql.SQL("GRANT CONNECT ON DATABASE {} TO {}").format(sql.Identifier(database), runtime)
        )
        setup.execute("REVOKE CREATE ON SCHEMA public FROM PUBLIC")
        setup.execute(sql.SQL("GRANT USAGE ON SCHEMA public TO {}").format(runtime))
        setup.execute("""
            CREATE TABLE public.invoices (
                id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                tenant_id text NOT NULL,
                description text NOT NULL,
                amount_cents integer NOT NULL CHECK (amount_cents >= 0)
            )
        """)
        with setup.cursor() as cursor:
            cursor.executemany(
                "INSERT INTO public.invoices (id, tenant_id, description, amount_cents)"
                " VALUES (%s, %s, %s, %s)",
                dataset["invoices"],
            )
        highest = max(row[0] for row in dataset["invoices"])
        setup.execute(
            sql.SQL("ALTER TABLE public.invoices ALTER COLUMN id RESTART WITH {}").format(
                sql.Literal(highest + 1)
            )
        )
        setup.execute(
            sql.SQL("GRANT USAGE ON SEQUENCE public.invoices_id_seq TO {}").format(runtime)
        )
        if fixture == "plain":
            setup.execute(
                sql.SQL("GRANT SELECT, INSERT, UPDATE ON public.invoices TO {}").format(runtime)
            )
        else:
            setup.execute(
                f"ALTER TABLE public.invoices ALTER COLUMN tenant_id SET DEFAULT {_CONTEXT}"
            )
            setup.execute("ALTER TABLE public.invoices ENABLE ROW LEVEL SECURITY")
            setup.execute("ALTER TABLE public.invoices FORCE ROW LEVEL SECURITY")
            setup.execute(sql.SQL("GRANT SELECT ON public.invoices TO {}").format(runtime))
            setup.execute(
                sql.SQL(
                    "GRANT INSERT (description, amount_cents), "
                    "UPDATE (description, amount_cents) ON public.invoices TO {}"
                ).format(runtime)
            )
            setup.execute(
                sql.SQL(
                    "CREATE POLICY tenant_isolation ON public.invoices FOR ALL TO {} "
                    f"USING (tenant_id = {_CONTEXT}) WITH CHECK (tenant_id = {_CONTEXT})"
                ).format(runtime)
            )
    return setup_dsn
